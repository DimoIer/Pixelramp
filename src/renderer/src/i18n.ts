function interpolate(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, key) =>
    key in vars ? String(vars[key]) : match
  )
}

export function translate(language: Language, text: string): string {
  return language === 'en' ? EN[text] ?? text : text
}

export function tr(text: string, vars?: Record<string, string | number>): string {
  return interpolate(translate(usePreferences.getState().language, text), vars)
}

export function useT(): (text: string, vars?: Record<string, string | number>) => string {
  const language = usePreferences((state) => state.language)
  return useCallback(
    (text: string, vars?: Record<string, string | number>) =>
      interpolate(translate(language, text), vars),
    [language]
  )
}
